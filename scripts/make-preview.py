"""Package one VoxelWorld OBJ into an offline, interactive browser preview."""

import argparse
from array import array
from base64 import b64encode
import json
from pathlib import Path
import sys


def package_mesh(mesh_path, out_path):
    vertices = []
    invokers = []
    windows = []
    camera = None
    density = 1.0
    spacing = None
    positions = array("d")
    levels = bytearray()
    level = 3
    with mesh_path.open(encoding="utf-8") as mesh:
        for line in mesh:
            if line.startswith("# voxel_density "):
                density = float(line.split()[2])
            elif line.startswith("# finest_spacing_m "):
                spacing = float(line.split()[2])
            elif line.startswith("# invoker "):
                invokers.append([float(value) for value in line.split()[2:5]])
            elif line.startswith("# camera_invoker "):
                camera = [float(value) for value in line.split()[2:5]]
            elif line.startswith("# clipmap "):
                _, _, invoker, lod, *coords = line.split()
                windows.append([int(invoker), int(lod), *map(float, coords)])
            elif line.startswith("o "):
                level = int(line.rsplit("_LOD", 1)[1]) if "_LOD" in line else 3
            elif line.startswith("v "):
                vertices.append(tuple(float(value) for value in line.split()[1:4]))
            elif line.startswith("f "):
                indices = [int(value.split("/")[0]) for value in line.split()[1:]]
                if len(indices) != 3 or level not in range(254) or any(index < 1 for index in indices):
                    raise ValueError("Expected an OBJ generated by VoxelWorld")
                for index in indices:
                    positions.extend(vertices[index - 1])
                    levels.append(level)
    if not invokers or not positions:
        raise ValueError("OBJ lacks terrain or Invoker metadata. Regenerate it with the current voxel_world --global --obj.")
    if sys.byteorder != "little":
        positions.byteswap()
    template = (Path(__file__).parent / "preview.html").read_text(encoding="utf-8")
    data = {
        "invokers": invokers,
        "voxelDensity": density,
        "finestSpacingM": spacing if spacing is not None else 50 * density,
        "camera": camera,
        "windows": windows,
        "positions": b64encode(positions).decode("ascii"),
        "levels": b64encode(levels).decode("ascii"),
    }
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(template.replace("/* MESH_DATA */ null", json.dumps(data, separators=(",", ":"))), encoding="utf-8")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("obj", type=Path)
    parser.add_argument("html", type=Path)
    args = parser.parse_args()
    package_mesh(args.obj, args.html)
